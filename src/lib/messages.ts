export type MessageKey = keyof (typeof DICT)["es"];

export function t(locale: Locale, key: MessageKey, vars?: Record<string, string | number>): string {
  let text: string = DICT[locale][key] ?? DICT.es[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) text = text.replace(`{${k}}`, String(v));
  return text;
}

/**
 * Looks up a dynamic key (e.g. a status contract `key` like `document.status.pending`) and
 * returns `null` when it is absent, so callers can fall back instead of echoing the raw key.
 */
export function tOptional(locale: Locale, key: string): string | null {
  const dict = DICT[locale] as Record<string, string>;
  return dict[key] ?? (DICT.es as Record<string, string>)[key] ?? null;
}
